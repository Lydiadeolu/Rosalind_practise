import itertools

def parse_fasta(fasta_text):
    """
    Parses FASTA format string and returns the combined DNA string.
    """
    lines = fasta_text.strip().split("\n")
    sequence_parts = []
    for line in lines:
        line = line.strip()
        if not line:
            continue
        if line.startswith(">"):
            continue
        sequence_parts.append(line)
    return "".join(sequence_parts)

def compute_4mer_composition(dna_seq):
    """
    Computes the 4-mer composition of a DNA sequence in lexicographical order.
    
    Returns:
        list: 256 integer counts of each 4-mer.
    """
    bases = ['A', 'C', 'G', 'T']
    
    kmers = [''.join(p) for p in itertools.product(bases, repeat=4)]
    
    kmer_counts = {kmer: 0 for kmer in kmers}
    
    for i in range(len(dna_seq) - 3):
        kmer = dna_seq[i:i+4]
        if kmer in kmer_counts:
            kmer_counts[kmer] += 1
            
    return [kmer_counts[k] for k in kmers]

